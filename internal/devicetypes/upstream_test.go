var update = flag.Bool("update", false, "rewrite docs/reference/devicetypes-catalogue.md from the embedded library")

// notVendorDirs are the directories of the library that hold no upstream model
// file: the others are named after a manufacturer.
var notVendorDirs = map[string]bool{
	"trica": true, devicetypes.ImageDir: true, devicetypes.DrawingDir: true, devicetypes.LayoutDir: true, devicetypes.OverlayDir: true,
}

// vendorFiles lists, relative to library/, the model files of the vendor
// directories: the ones copied from upstream.
func vendorFiles(t *testing.T) map[string][]byte {
	t.Helper()
	lib := os.DirFS("library")
	out := map[string][]byte{}
	dirs, err := fs.ReadDir(lib, ".")
	if err != nil {
		t.Fatal(err)
	}
	for _, d := range dirs {
		if !d.IsDir() || notVendorDirs[d.Name()] || strings.HasPrefix(d.Name(), ".") {
			continue
		}
		err := fs.WalkDir(lib, d.Name(), func(p string, e fs.DirEntry, err error) error {
			if err != nil || e.IsDir() || (!strings.HasSuffix(p, ".yaml") && !strings.HasSuffix(p, ".yml")) {
				return err
			}
			data, err := fs.ReadFile(lib, p)
			out[p] = data
			return err
		})
		if err != nil {
			t.Fatal(err)
		}
	}
	return out
}

// gitBlob is the id git gives a file: sha1("blob <size>\0" + content).
func gitBlob(data []byte) string {
	h := sha1.New()
	fmt.Fprintf(h, "blob %d\x00", len(data))
	h.Write(data)
	return hex.EncodeToString(h.Sum(nil))
}

// The files copied from netbox-community/devicetype-library are copied
// unchanged (ADR 0056): upstream.tsv lists every file of a vendor directory
// with the commit it was copied at and its git blob, scripts/devicetype-library/fetch.sh
// writes it, and this test recomputes the blobs. Editing a file, adding one
// that is not upstream's, or deleting one makes it fail: a change to a model
// belongs in library/trica/ (or the overlay), not in a copy.
func TestUpstreamFilesAreUnchanged(t *testing.T) {
	raw, err := os.ReadFile("library/upstream.tsv")
	if err != nil {
		t.Fatal(err)
	}
	commit := regexp.MustCompile(`^[0-9a-f]{40}$`)
	manifest := map[string][2]string{}
	var paths []string
	for i, line := range strings.Split(strings.TrimSuffix(string(raw), "\n"), "\n") {
		f := strings.Split(line, "\t")
		if len(f) != 3 || !commit.MatchString(f[1]) || !commit.MatchString(f[2]) {
			t.Fatalf("upstream.tsv line %d: want <path> TAB <commit> TAB <blob>, got %q", i+1, line)
		}
		if _, dup := manifest[f[0]]; dup {
			t.Fatalf("upstream.tsv lists %s twice", f[0])
		}
		manifest[f[0]] = [2]string{f[1], f[2]}
		paths = append(paths, f[0])
	}
	if !sort.StringsAreSorted(paths) {
		t.Error("upstream.tsv is not sorted by path (fetch.sh keeps it so)")
	}
	files := vendorFiles(t)
	for p, data := range files {
		m, ok := manifest[p]
		switch {
		case !ok:
			t.Errorf("%s is in a vendor directory but not in upstream.tsv: copy it with scripts/devicetype-library/fetch.sh, or put a model of the project in library/trica/", p)
		case gitBlob(data) != m[1]:
			t.Errorf("%s changed: its git blob is %s, upstream.tsv says %s at %s", p, gitBlob(data), m[1], m[0])
		}
	}
	for p := range manifest {
		if _, ok := files[p]; !ok {
			t.Errorf("upstream.tsv lists %s, which is not in the library", p)
		}
	}
	if len(files) < 440 {
		t.Errorf("%d upstream files, want at least the 447 of ADR 0056", len(files))
	}
}

// catalogueDoc renders the list of every model of the library.
func catalogueDoc(models []*devicetypes.Model) string {
	byVendor := map[string][]*devicetypes.Model{}
	var vendors []string
	for _, m := range models {
		if _, ok := byVendor[m.Vendor]; !ok {
			vendors = append(vendors, m.Vendor)
		}
		byVendor[m.Vendor] = append(byVendor[m.Vendor], m)
	}
	sort.Slice(vendors, func(i, j int) bool { return strings.ToLower(vendors[i]) < strings.ToLower(vendors[j]) })
	face := func(img *devicetypes.Image) string {
		switch {
		case img == nil:
			return "—"
		case img.Origin == devicetypes.OriginUpstream:
			return "NetBox"
		default:
			return "drawn"
		}
	}
	var b strings.Builder
	b.WriteString("# Device-type catalogue\n\n")
	b.WriteString("<!-- Generated by `go test ./internal/devicetypes/ -run TestCatalogueListIsCurrent -update` from the embedded library. Do not edit. -->\n\n")
	fmt.Fprintf(&b, "Every one of the %d models of the embedded library, by manufacturer (see [the library](devicetypes.md)).\n\n", len(models))
	b.WriteString("**U** is the rack height (0: occupies no rack unit, a desktop or wall device). **Front** and **Rear**: ")
	b.WriteString("NetBox = upstream CC0 photograph, drawn = schematic face drawn by the project, — = none. ")
	b.WriteString("↳ marks a chassis variant (`variant_of`). **SKUs** are the `part_numbers` that match a device by part number.\n")
	for _, v := range vendors {
		ms := byVendor[v]
		sort.Slice(ms, func(i, j int) bool { return ms[i].Slug < ms[j].Slug })
		fmt.Fprintf(&b, "\n## %s (%d models)\n\n| Model | Slug | U | Front | Rear | SKUs |\n|---|---|---|---|---|---|\n", v, len(ms))
		for _, m := range ms {
			name := strings.ReplaceAll(m.Model, "|", "\\|")
			if !strings.HasPrefix(strings.ToLower(name), strings.ToLower(v)) {
				name = v + " " + name
			}
			if m.VariantOf != "" {
				name = "↳ " + name
			}
			fmt.Fprintf(&b, "| %s | `%s` | %g | %s | %s | %s |\n", name, m.Slug, m.UHeight, face(m.FrontImage), face(m.RearImage), strings.Join(m.PartNumbers, ", "))
		}
	}
	return b.String()
}

// The list of the models in docs/reference/devicetypes-catalogue.md is
// generated, so that it cannot miss a file (there were 191 hand-written rows
// and 7 models they did not list). With -update the test rewrites it.
func TestCatalogueListIsCurrent(t *testing.T) {
	models, err := devicetypes.Default()
	if err != nil {
		t.Fatal(err)
	}
	const doc = "../../docs/reference/devicetypes-catalogue.md"
	want := catalogueDoc(models)
	if *update {
		if err := os.WriteFile(doc, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(doc)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != want {
		t.Errorf("%s is out of date: run `go test ./internal/devicetypes/ -run TestCatalogueListIsCurrent -update` and commit it", doc)
	}
	// Every model is in the list (the doc is compared whole above; this
	// names what a hand edit would have dropped).
	for _, m := range models {
		if !strings.Contains(string(got), "`"+m.Slug+"`") {
			t.Errorf("%s is not in the catalogue list", m.Slug)
		}
	}
}
